export const STORAGE_KEY = 'mdc-language';
let language = 'en';
export const resolveLanguage = value => value === 'zh' ? 'zh' : 'en';
export const getLanguage = () => language;
export function t(key, values = {}, locale = language) {
  const template = locale === 'zh' ? key : (messages[key] ?? key);
  return template.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}
export function preferredLanguage(storage) {
  try { return resolveLanguage(storage?.getItem(STORAGE_KEY)); } catch { return 'en'; }
}
export function applyTranslations(doc) {
  doc.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  for (const [data, attribute] of [['i18n',null],['i18n-aria','aria-label'],['i18n-title','title'],['i18n-content','content']]) {
    doc.querySelectorAll('[data-'+data+']').forEach(node => {
      const value = t(node.getAttribute('data-'+data));
      if (attribute) node.setAttribute(attribute,value); else node.textContent=value;
    });
  }
  doc.querySelectorAll('[data-language]').forEach(node => node.setAttribute('aria-pressed',String(node.dataset.language===language)));
}
export function setLanguage(value, {doc=globalThis.document,storage}={}) {
  language=resolveLanguage(value);
  try { storage?.setItem(STORAGE_KEY,language); } catch { /* Private browsing may disable storage. */ }
  if(doc) {
    applyTranslations(doc);
    doc.dispatchEvent(new CustomEvent('mdc:languagechange'));
  }
  return language;
}
export function initI18n(doc) {
  let storage;
  try { storage=globalThis.localStorage; } catch { /* Default English remains usable. */ }
  setLanguage(preferredLanguage(storage),{doc,storage});
  doc.querySelectorAll('[data-language]').forEach(node=>node.addEventListener('click',()=>setLanguage(node.dataset.language,{doc,storage})));
}
if(typeof document!=='undefined') initI18n(document);
